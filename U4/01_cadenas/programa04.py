entero = 56
decimal = 5.6
booleano = False

#pasar a str

entero = str(entero)
decimal = str(decimal)
booleano = str(booleano)

print(type(entero), type(decimal), type(booleano))

#pasar a int, float y bool

entero = int(entero)
decimal = float(decimal)
booleano = bool(booleano)

print(type(entero), type(decimal), type(booleano))

